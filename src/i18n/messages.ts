export type MessageKey = keyof typeof messages

export function categoryKey(id: string): MessageKey {
  const key = `cat.${id}`
  return key in messages ? (key as MessageKey) : 'cat.other'
}

export function translate(language: Lang, key: MessageKey, vars?: Record<string, string | number>) {
  const template = messages[key][language]
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''))
}
